/* ── SCIM 2.0: THE COMPANY'S DIRECTORY ADDS AND REMOVES ITS PEOPLE ──────────

   The failure this exists for: somebody leaves a company and keeps the
   company's chats and files, because removing them from AMV depended on an
   admin remembering. A company's identity provider (Okta, Microsoft Entra ID,
   Google Workspace, OneLogin) can do it within minutes over SCIM - and a
   security review asks for exactly this before anything else.

   Decided by the owner's delegation (docs/OWNER-DECISIONS.md #1): Users only.
   Groups map to roles, and no new roles are being added yet.

   THE BOUNDS, each one enforced here:
     - The token is the team's, generated by its OWNER in the company sign-in
       settings, shown once, and stored only as a SHA-256 hash. It carries the
       team id, so no index is needed to find the team it belongs to.
     - SCIM needs company sign-in with a PROVED domain, and only manages
       addresses at that domain. A directory can never pull an outsider's
       account into the team, and members at other addresses (a contractor on
       their own mail) are not the directory's to see or remove.
     - The team's OWNER is never removed or changed through SCIM: they are the
       way back in.
     - Removing somebody (DELETE, or active set to false) takes them off the
       team AND ends every sign-in they have, so the access ends now, not when
       a token expires.
     - Adding somebody holds a seat, inside the team lock, against the plan's
       seat limit; somebody already in another AMV team is refused rather than
       moved.
     - Every call that changes anything is in the team's audit log; every call
       is rate-limited per team.
     - The emergency stop does not stop it: cutting off access is a security
       action, and the stop exists to stop spending. */
const SCIM_USER = 'urn:ietf:params:scim:schemas:core:2.0:User';
const SCIM_LIST = 'urn:ietf:params:scim:api:messages:2.0:ListResponse';
const SCIM_ERR  = 'urn:ietf:params:scim:api:messages:2.0:Error';
const SCIM_PATCH = 'urn:ietf:params:scim:api:messages:2.0:PatchOp';
const SCIM_PAGE_MAX = 200;
const SCIM_OFF_KEEP = 500;

const _scimJson = (obj, status = 200, extra) => new Response(JSON.stringify(obj), { status,
  headers: { 'Content-Type': 'application/scim+json; charset=utf-8', 'Cache-Control': 'no-store', ...SECURITY_HEADERS, ...(extra || {}) } });
const _scimErr = (status, detail, scimType) => _scimJson({ schemas: [SCIM_ERR], status: String(status), detail, ...(scimType ? { scimType } : {}) }, status);

async function _scimHash(s){
  return [...new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(String(s))))].map(b => b.toString(16).padStart(2, '0')).join('');
}
/* A stable id per address and team, computed rather than stored. */
async function _scimId(teamId, email){ return 'u' + (await _scimHash(teamId + ':' + String(email).toLowerCase())).slice(0, 24); }
function _scimNewToken(teamId){
  const secret = [...crypto.getRandomValues(new Uint8Array(32))].map(b => b.toString(16).padStart(2, '0')).join('');
  return 'amvscim_' + teamId + '_' + secret;
}

/* Owner's half, called from teamSso: switch SCIM on (a new token, shown once,
   replacing any earlier one) or off. */
async function _scimOwnerAction(request, env, team, user, on){
  if(!on){
    try{ await _withTeam(env, team.id, (fresh) => { if(fresh) delete fresh.scim; return true; }); }
    catch(e){ if(!_isBusy(e)) throw e; return _busyJson('team'); }
    await _teamAudit(env, team, user.email, 'scim_off', {});
    return json({ ok:true, scim: null });
  }
  if(!team.sso || !team.sso.verified)
    return json({ error:'Prove your company’s domain first: the directory can only manage addresses at it.', code:'not_verified' }, 400);
  const token = _scimNewToken(team.id);
  const hash = await _scimHash(token);
  const at = Date.now();
  try{ await _withTeam(env, team.id, (fresh) => { if(fresh) fresh.scim = { hash, at, tail: token.slice(-4) }; return true; }); }
  catch(e){ if(!_isBusy(e)) throw e; return _busyJson('team'); }
  await _teamAudit(env, team, user.email, 'scim_token_created', { tail: token.slice(-4) });
  return json({ ok:true, scim: { on: true, at, tail: token.slice(-4) }, token,
                baseUrl: _publicOrigin(request) + '/scim/v2' });
}

async function _scimTeam(request, env){
  const m = /^Bearer\s+(amvscim_(team_[a-f0-9]{32})_[a-f0-9]{64})$/.exec(String(request.headers.get('Authorization') || ''));
  if(!m) return null;
  const team = await DB.get(env, 'team', m[2]);
  if(!team || !team.scim || !team.scim.hash) return null;
  if(!timingSafeEqual(await _scimHash(m[1]), team.scim.hash)) return null;
  /* Company sign-in un-proved or removed since: SCIM stops with it. */
  if(!team.sso || !team.sso.verified) return null;
  return team;
}
async function _scimUser(request, team, member, active){
  const email = String(member.email).toLowerCase();
  const id = await _scimId(team.id, email);
  return { schemas: [SCIM_USER], id, userName: email, active,
           ...(member.name ? { name: { formatted: String(member.name).slice(0, 120) }, displayName: String(member.name).slice(0, 120) } : {}),
           emails: [{ value: email, primary: true, type: 'work' }],
           meta: { resourceType: 'User', created: new Date(member.joinedAt || member.at || Date.now()).toISOString(),
                   lastModified: new Date(member.at || member.joinedAt || Date.now()).toISOString(),
                   location: new URL('/scim/v2/Users/' + id, request.url).toString() } };
}
/* Everybody the directory may see: members at the proved domain, and people
   it switched off (so it can switch them back on). */
async function _scimAll(request, team){
  const dom = team.sso.domain;
  const out = [];
  for(const m of team.members || []) if(_ssoDomainOf(m.email) === dom) out.push(await _scimUser(request, team, m, true));
  for(const o of team.scimOff || []) if(!(team.members || []).some(m => m.email === o.email)) out.push(await _scimUser(request, team, o, false));
  return out;
}
/* Strict, because the wrong answer here switches somebody off. A directory
   sending {"active":"banana"} has a bug, and reading it as false would end an
   employee's every sign-in on the strength of that bug. true/false, or the
   strings Entra ID sends ("True"/"False"); anything else is refused. */
const _scimBool = (v) => {
  if(v === true || v === false) return v;
  const t = typeof v === 'string' ? v.trim().toLowerCase() : '';
  return t === 'true' ? true : t === 'false' ? false : null;
};
const _SCIM_BAD_ACTIVE = 'active must be true or false.';

async function _scimAdd(env, team, email, name){
  if(_ssoDomainOf(email) !== team.sso.domain) return { status: 400, detail: 'Only addresses at ' + team.sso.domain + ' can be managed here.', type: 'invalidValue' };
  const other = await env.AMV_KV.get('userteam:' + email);
  if(other && other !== team.id) return { status: 409, detail: 'That person is in another AMV team. They have to leave it first.', type: 'uniqueness' };
  let res;
  try{
    res = await _withTeam(env, team.id, (fresh) => {
      if(!fresh) return { status: 404, detail: 'team gone' };
      fresh.members = fresh.members || [];
      if(fresh.members.some(m => m.email === email)) return { already: true };
      const limit = _teamSeatLimit(_teamPlan(fresh), fresh.customCfg);
      if(fresh.members.length >= limit) return { status: 409, detail: 'The team has no free seats. The owner can add seats in AMV.', type: 'tooMany' };
      fresh.members.push({ email, role: 'member', joinedAt: Date.now(), via: 'scim', ...(name ? { name: String(name).slice(0, 120) } : {}) });
      fresh.scimOff = (fresh.scimOff || []).filter(o => o.email !== email);
      return { added: true };
    });
  }catch(e){ if(!_isBusy(e)) throw e; return { status: 503, detail: 'Busy - try again.' }; }
  if(res && res.status) return res;
  /* The same two pointers a join writes - and given back if they cannot be,
     so a seat is never held by somebody who cannot reach the team. */
  try{ await env.AMV_KV.put('userteam:' + email, team.id); await _setUserTeam(env, email, team.id); }
  catch(e){
    try{ await _withTeam(env, team.id, (fresh) => { if(fresh) fresh.members = (fresh.members || []).filter(m => m.email !== email); return true; }); }catch(_){}
    return { status: 503, detail: 'AMV could not finish adding them. Nothing was changed - try again.' };
  }
  if(res && res.added) await _teamAudit(env, team, 'scim', 'scim_user_added', { target: email });
  return { ok: true, already: !!(res && res.already) };
}
async function _scimRemove(env, team, email){
  if(String(team.ownerEmail || '').toLowerCase() === email)
    return { status: 400, detail: 'The team’s owner is managed in AMV, not by the directory.', type: 'mutability' };
  let removed = false;
  try{
    await _withTeam(env, team.id, (fresh) => {
      if(!fresh) return;
      const m = (fresh.members || []).find(x => x.email === email);
      if(!m || m.role === 'owner') return;
      fresh.members = fresh.members.filter(x => x.email !== email);
      fresh.scimOff = (fresh.scimOff || []).filter(o => o.email !== email)
        .concat({ email, name: m.name || '', at: Date.now(), joinedAt: m.joinedAt || 0 }).slice(-SCIM_OFF_KEEP);
      removed = true;
    });
  }catch(e){ if(!_isBusy(e)) throw e; return { status: 503, detail: 'Busy - try again.' }; }
  if(removed){
    if((await env.AMV_KV.get('userteam:' + email)) === team.id) await env.AMV_KV.delete('userteam:' + email);
    await _setUserTeam(env, email, null);
    /* Now, not when a token runs out. */
    await revokeUserTokens(env, email);
    await _teamAudit(env, team, 'scim', 'scim_user_removed', { target: email });
  }
  return { ok: true, removed };
}

async function scimRoute(request, env, path){
  const team = await _scimTeam(request, env);
  if(!team) return _scimErr(401, 'The token is missing, wrong, or has been replaced.');
  const lim = await limitAction(env, 'scim:' + team.id, 120, 20000);
  if(!lim.ok) return _scimErr(lim.unavailable ? 503 : 429, lim.unavailable ? 'Try again in a moment.' : 'Too many requests. Slow down.');
  const sub = path.replace(/^\/scim\/v2\/?/, '').replace(/\/$/, '');
  const method = request.method;

  if(sub === 'ServiceProviderConfig' && method === 'GET')
    return _scimJson({ schemas: ['urn:ietf:params:scim:schemas:core:2.0:ServiceProviderConfig'],
      patch: { supported: true }, bulk: { supported: false, maxOperations: 0, maxPayloadSize: 0 },
      filter: { supported: true, maxResults: SCIM_PAGE_MAX }, changePassword: { supported: false },
      sort: { supported: false }, etag: { supported: false },
      authenticationSchemes: [{ type: 'oauthbearertoken', name: 'Bearer token', description: 'The token from AMV’s company sign-in settings.' }] });

  if(sub === 'Users' && method === 'GET'){
    const u = new URL(request.url);
    let all = await _scimAll(request, team);
    const f = /^\s*userName\s+eq\s+"([^"]{1,320})"\s*$/i.exec(u.searchParams.get('filter') || '');
    if(u.searchParams.get('filter') && !f) return _scimErr(400, 'Only userName eq "address" is supported.', 'invalidFilter');
    if(f) all = all.filter(x => x.userName === f[1].toLowerCase());
    const start = Math.max(1, Number(u.searchParams.get('startIndex')) || 1);
    const count = Math.min(SCIM_PAGE_MAX, Math.max(0, Number(u.searchParams.get('count') ?? SCIM_PAGE_MAX) || 0));
    const page = all.slice(start - 1, start - 1 + count);
    return _scimJson({ schemas: [SCIM_LIST], totalResults: all.length, startIndex: start, itemsPerPage: page.length, Resources: page });
  }

  if(sub === 'Users' && method === 'POST'){
    const body = await request.json().catch(() => null);
    const email = String((body && (body.userName || (Array.isArray(body.emails) && body.emails[0] && body.emails[0].value))) || '').trim().toLowerCase();
    if(!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || email.length > 254) return _scimErr(400, 'userName must be an email address.', 'invalidValue');
    if(body && body.active != null && _scimBool(body.active) === null) return _scimErr(400, _SCIM_BAD_ACTIVE, 'invalidValue');
    if(body && body.active != null && !_scimBool(body.active)) return _scimErr(400, 'A new user is created active.', 'invalidValue');
    const fresh = await DB.get(env, 'team', team.id);
    if((fresh.members || []).some(m => m.email === email)) return _scimErr(409, 'That person is already in the team.', 'uniqueness');
    const name = body && (body.displayName || (body.name && (body.name.formatted || [body.name.givenName, body.name.familyName].filter(Boolean).join(' '))));
    const r = await _scimAdd(env, fresh, email, name);
    if(r.status) return _scimErr(r.status, r.detail, r.type);
    const after = await DB.get(env, 'team', team.id);
    const m = (after.members || []).find(x => x.email === email);
    return _scimJson(await _scimUser(request, after, m, true), 201);
  }

  const one = /^Users\/(u[a-f0-9]{24})$/.exec(sub);
  if(one){
    const all = await _scimAll(request, team);
    const cur = all.find(x => x.id === one[1]);
    if(!cur) return _scimErr(404, 'No such user in this team.');
    const email = cur.userName;
    if(method === 'GET') return _scimJson(cur);
    if(method === 'DELETE'){
      const r = await _scimRemove(env, team, email);
      if(r.status) return _scimErr(r.status, r.detail, r.type);
      return new Response(null, { status: 204, headers: { ...SECURITY_HEADERS } });
    }
    let active = null;
    if(method === 'PUT'){
      const body = await request.json().catch(() => null);
      if(!body) return _scimErr(400, 'Send the user as JSON.', 'invalidSyntax');
      if(body.userName && String(body.userName).toLowerCase() !== email) return _scimErr(400, 'An address cannot be changed; add the new address as a new user.', 'mutability');
      active = body.active == null ? cur.active : _scimBool(body.active);
      if(active === null) return _scimErr(400, _SCIM_BAD_ACTIVE, 'invalidValue');
    } else if(method === 'PATCH'){
      const body = await request.json().catch(() => null);
      const ops = body && Array.isArray(body.Operations) ? body.Operations : null;
      if(!ops) return _scimErr(400, 'Send a PatchOp with Operations.', 'invalidSyntax');
      for(const op of ops.slice(0, 20)){
        const kind = String(op && op.op || '').toLowerCase();
        if(kind !== 'replace' && kind !== 'add') continue;
        const p = String(op.path || '').toLowerCase();
        /* Every operation is checked before any is applied: a request with
           one bad value changes nothing. */
        if(p === 'active'){ active = _scimBool(op.value); if(active === null) return _scimErr(400, _SCIM_BAD_ACTIVE, 'invalidValue'); }
        else if(!p && op.value && typeof op.value === 'object' && 'active' in op.value){
          active = _scimBool(op.value.active); if(active === null) return _scimErr(400, _SCIM_BAD_ACTIVE, 'invalidValue'); }
        else if(p === 'username' || (op.value && op.value.userName && String(op.value.userName).toLowerCase() !== email))
          return _scimErr(400, 'An address cannot be changed; add the new address as a new user.', 'mutability');
      }
    } else return _scimErr(405, 'That method is not supported here.');
    if(active === false && cur.active){
      const r = await _scimRemove(env, team, email);
      if(r.status) return _scimErr(r.status, r.detail, r.type);
    } else if(active === true && !cur.active){
      const r = await _scimAdd(env, team, email, '');
      if(r.status) return _scimErr(r.status, r.detail, r.type);
    }
    const after = await DB.get(env, 'team', team.id);
    const now = await _scimAll(request, after);
    return _scimJson(now.find(x => x.id === one[1]) || Object.assign({}, cur, { active: active === null ? cur.active : active }));
  }
  return _scimErr(404, 'Not found. Users and ServiceProviderConfig are supported.');
}
