/* What share of the services Crew names, per country, a person can find in
   that country's Integrations - and which are not there yet.

     node scripts/crew-services-report.mjs   -> docs/CREW-SERVICES.md

   "Findable" is what a search there finds: the name inside a listed
   service's name (JPMorgan Chase for Chase), or the name as a listed site's
   own domain (commbank.com.au for CommBank). Listed means an app AMV
   connects, the country's own catalogue, a worldwide service, or a Crew
   service whose lookup was believed (crew-services.mjs, trustedMatch). */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { buildGlobalServices, appNames } from './global-services.mjs';
import { countryFacts, namesIn, plainName, FACT_TOPIC } from './crew-services.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const siteLabel = (h) => { const p = String(h || '').toLowerCase().split('.'); p.pop();
  if (p.length > 1 && /^(com|co|gov|gob|org|net|ac|edu|go|or|ne|gv|gouv|bank|nic|gub)$/.test(p[p.length - 1])) p.pop();
  return (p[p.length - 1] || '').replace(/-/g, ''); };

export function crewCoverage(root = ROOT, built = buildGlobalServices(root)) {
  const g = JSON.parse(built.services);
  const appRows = appNames(root).flatMap(c => c.names.map(n => [String(n), '']));
  const facts = countryFacts(root);
  let named = 0, found = 0; const per = {}, missing = {};
  for (const [cc, F] of Object.entries(facts)) {
    let cf = null; try { cf = JSON.parse(readFileSync(join(root, 'data', 'countries', cc + '.json'), 'utf8')); } catch (e) {}
    const rows = [...appRows, ...(cf ? Object.values(cf.kinds || {}).flat().map(e => [e.n, e.s]) : []), ...g.entries.map(e => [e[1], e[2]]),
      ...((JSON.parse(built.countries[cc] || '{"crew":[]}').crew || []).map(r => [r[1], r[2]]))];
    const idx = rows.map(([n, s]) => [' ' + plainName(n) + ' ', siteLabel(s)]);
    let a = 0, b = 0; const seen = new Set();
    for (const [k, v] of Object.entries(F)) {
      if (!FACT_TOPIC[k]) continue;
      for (const n of namesIn(v)) {
        const p = plainName(n), c = p.replace(/ /g, '');
        if (!p || seen.has(p)) continue; seen.add(p);
        a++; named++;
        if (idx.some(([rn, rs]) => rn.includes(' ' + p + ' ') || (c.length >= 3 && rs === c))) { b++; found++; }
        else (missing[cc] = missing[cc] || []).push(n);
      }
    }
    per[cc] = { named: a, found: b };
  }
  return { named, found, per, missing };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const c = crewCoverage();
  const pct = (x, y) => y ? (100 * x / y).toFixed(0) + '%' : '-';
  const lines = ['# Services Crew names, findable in Integrations', '',
    'Generated by `node scripts/crew-services-report.mjs` from `COUNTRY_FACTS` (src/worker/65-country-capabilities.js),',
    'the believed lookups in `data/crew-services/` and what the build lists. Not found yet means the lookup found',
    'nothing that passed the checks - it is listed here rather than guessed at.', '',
    `**${c.found} of ${c.named} (${pct(c.found, c.named)})** are findable in their country's Integrations.`, '',
    '| Country | Findable | Not found yet |', '|---|---|---|'];
  for (const cc of Object.keys(c.per).sort()) lines.push(`| ${cc} | ${c.per[cc].found}/${c.per[cc].named} (${pct(c.per[cc].found, c.per[cc].named)}) | ${(c.missing[cc] || []).join(', ') || '-'} |`);
  writeFileSync(join(ROOT, 'docs', 'CREW-SERVICES.md'), lines.join('\n') + '\n');
  console.log(c.found, 'of', c.named, 'findable; docs/CREW-SERVICES.md written');
}
